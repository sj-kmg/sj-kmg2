/** 분류 → 기자재명 → 규격 순 정렬 (원본 순서 유지를 위해 등록 순서를 우선한다) */
export function compareInventory(a: InventoryItem, b: InventoryItem): number {
  const ca = INVENTORY_CATEGORIES.indexOf(a.category);
  const cb = INVENTORY_CATEGORIES.indexOf(b.category);
  if (ca !== cb) return (ca < 0 ? 99 : ca) - (cb < 0 ? 99 : cb);
  return a.id.localeCompare(b.id, 'en', { numeric: true });
}

